def iso965(d, p):
    """6g / 6H limits in mm, or None where ISO 965-1 defines no grade 6 values."""
    if d <= 1.4 or p not in ISO965_P:
        return None
    for (lo, hi), tab in ISO965_D2.items():
        if lo < d <= hi:
            if p not in tab:
                return None
            es, td, td1 = ISO965_P[p]
            td2, TD2 = tab[p]
            return {'es': es / 1000, 'Td': td / 1000, 'TD1': td1 / 1000,
                    'Td2': td2 / 1000, 'TD2': TD2 / 1000}
    return None


